import CoreHaptics
import Foundation

/// Captures the current draft as a standalone SwiftUI/Core Haptics example.
@MainActor
enum HapticSwiftExport {
    static func source(for configuration: CustomHapticConfiguration,
                       capabilities: HapticEventCapabilities) throws -> String {
        // Use the same validation, parameter omission, Float conversion, and timing as Play.
        let events = try HapticsController.hapticEvents(configuration, capabilities: capabilities)
        let parameterLines = configuration.activeParameters.compactMap { parameter -> String? in
            guard capabilities.ranges[parameter] != nil else { return nil }
            let name: String
            switch parameter {
            case .intensity: name = "hapticIntensity"
            case .sharpness: name = "hapticSharpness"
            case .attack: name = "attackTime"
            case .decay: name = "decayTime"
            case .release: name = "releaseTime"
            case .sustained: name = "sustained"
            }
            return "            CHHapticEventParameter(parameterID: .\(name), value: \(Float(configuration.value(for: parameter))))"
        }.joined(separator: ",\n")
        let eventType = configuration.isContinuous ? "hapticContinuous" : "hapticTransient"
        let eventLines = events.map {
            "            CHHapticEvent(eventType: .\(eventType), parameters: parameters, relativeTime: \($0.relativeTime), duration: \($0.duration))"
        }.joined(separator: ",\n")
        return """
        // Generated by Haptics Lab. Swift 6, iOS 26.0+.
        // Add this file to an iOS app and present ExportedHapticView().
        // Requires a physical device supporting Core Haptics; no audio is played.
        // Repetitions: \(configuration.pulseCount). Gap: \(configuration.gap) seconds.
        // Envelope times are relative values, not seconds.
        // Only parameters active and available on the exporting device are included.
        // Playback validates them on the destination device; tactile results can differ.
        import SwiftUI
        import CoreHaptics
        import Observation

        @MainActor
        struct ExportedHapticView: View {
            @State private var player = ExportedHapticPlayer()
            @Environment(\\.scenePhase) private var scenePhase

            var body: some View {
                Button {
                    if player.isPlaying { player.stop() } else { player.play() }
                } label: {
                    if player.isPlaying {
                        Label("Stop haptic", systemImage: "stop.fill")
                    } else {
                        Label("Play haptic", systemImage: "play.fill")
                    }
                }
                .padding()
                .onDisappear { player.stop() }
                .onChange(of: scenePhase) { _, phase in
                    if phase != .active { player.stop() }
                }
                .alert("Playback unavailable", isPresented: Binding(
                    get: { player.errorMessage != nil },
                    set: { if !$0 { player.errorMessage = nil } }
                )) {
                    Button("OK", role: .cancel) { player.errorMessage = nil }
                } message: {
                    Text(player.errorMessage ?? "")
                }
            }
        }

        @MainActor
        @Observable
        final class ExportedHapticPlayer {
            private(set) var isPlaying = false
            var errorMessage: String?
            @ObservationIgnored private var engine: CHHapticEngine?
            @ObservationIgnored private var player: (any CHHapticAdvancedPatternPlayer)?
            @ObservationIgnored private var startupTask: Task<Void, Never>?
            @ObservationIgnored private var generation: UInt64 = 0
            @ObservationIgnored private var engineIdentity: UUID?

            static func makeEvents() -> [CHHapticEvent] {
                let parameters = [
        \(parameterLines)
                ]
                return [
        \(eventLines)
                ]
            }

            private static func makePattern() throws -> CHHapticPattern {
                let events = makeEvents()
                let hardware = CHHapticEngine.capabilitiesForHardware()
                guard hardware.supportsHaptics else { throw PlaybackError.unsupported }
                for event in events {
                    for parameter in event.eventParameters {
                        let range = try hardware.attributes(forEventParameter: parameter.parameterID,
                                                            eventType: event.type)
                        guard parameter.value.isFinite,
                              parameter.value >= range.minValue,
                              parameter.value <= range.maxValue else {
                            throw PlaybackError.outsideDeviceRange
                        }
                    }
                }
                return try CHHapticPattern(events: events, parameters: [])
            }

            func play() {
                guard !isPlaying else { return }
                errorMessage = nil
                generation &+= 1
                let token = generation
                isPlaying = true
                startupTask = Task { [weak self] in
                    guard let self else { return }
                    do {
                        let pattern = try Self.makePattern()
                        let engine = try makeEngine()
                        try await engine.start()
                        guard token == generation, !Task.isCancelled else {
                            try? await engine.stop()
                            return
                        }
                        let player = try engine.makeAdvancedPlayer(with: pattern)
                        player.completionHandler = { [weak self] error in
                            let message = error?.localizedDescription
                            Task { @MainActor [weak self] in
                                self?.finish(token: token, message: message)
                            }
                        }
                        self.player = player
                        try player.start(atTime: CHHapticTimeImmediate)
                        startupTask = nil
                    } catch {
                        guard token == generation else { return }
                        finish(token: token,
                               message: error is CancellationError ? nil : error.localizedDescription)
                    }
                }
            }

            func stop() {
                generation &+= 1
                startupTask?.cancel()
                startupTask = nil
                try? player?.stop(atTime: CHHapticTimeImmediate)
                player = nil
                let oldEngine = engine
                engine = nil
                engineIdentity = nil
                oldEngine?.stop(completionHandler: nil)
                isPlaying = false
            }

            private func makeEngine() throws -> CHHapticEngine {
                if let engine { return engine }
                let newEngine = try CHHapticEngine()
                newEngine.playsHapticsOnly = true
                newEngine.isAutoShutdownEnabled = true
                let identity = UUID()
                engineIdentity = identity
                newEngine.stoppedHandler = { [weak self] _ in
                    Task { @MainActor [weak self] in self?.interrupted(identity: identity) }
                }
                newEngine.resetHandler = { [weak self] in
                    Task { @MainActor [weak self] in self?.interrupted(identity: identity) }
                }
                engine = newEngine
                return newEngine
            }

            private func interrupted(identity: UUID) {
                guard engineIdentity == identity else { return }
                let wasPlaying = isPlaying
                stop()
                if wasPlaying { errorMessage = "Playback interrupted. Tap Play to try again." }
            }

            private func finish(token: UInt64, message: String?) {
                guard token == generation else { return }
                isPlaying = false
                player = nil
                startupTask = nil
                errorMessage = message
            }

            private enum PlaybackError: LocalizedError {
                case unsupported, outsideDeviceRange
                var errorDescription: String? {
                    switch self {
                    case .unsupported: "This device does not support custom haptics."
                    case .outsideDeviceRange: "An exported value is outside this device's supported range."
                    }
                }
            }
        }

        """
    }
}
